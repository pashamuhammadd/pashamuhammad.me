import { getGitHubActivity } from "@/lib/github-activity";
import { getOgImage } from "@/lib/og-preview";
import { projects, site } from "@/lib/site-content";
import { SiteFooter, SiteHeader } from "@/components/home/SiteChrome";
import {
  Contact,
  DevlogSection,
  Hero,
  HowIBuild,
  SelectedWork,
  StackStrip,
} from "@/components/home/HomeSections";

// GitHub activity is re-fetched at most every 5 minutes (OG images daily).
export const revalidate = 300;

export default async function Home() {
  const [activity, previews] = await Promise.all([
    // Public activity only: no token, nothing private reaches the page.
    getGitHubActivity({ publicOnly: true }),
    Promise.all(
      projects.map((project) =>
        // This site's own preview is generated by app/opengraph-image.tsx.
        project.url === site.url ? Promise.resolve("/opengraph-image") : getOgImage(project.url)
      )
    ),
  ]);

  return (
    <div className="flex min-h-screen flex-col overflow-x-clip bg-[#1f1f27] font-sans text-[#f1f4ef] antialiased">
      <a
        href="#main"
        className="sr-only focus:not-sr-only focus:fixed focus:top-3 focus:left-3 focus:z-50 focus:rounded-[4px] focus:bg-[#00ce99] focus:px-4 focus:py-2 focus:font-semibold focus:text-[#08231a]"
      >
        Skip to content
      </a>
      <SiteHeader />
      <main id="main" className="flex-1">
        <Hero />
        <StackStrip />
        <SelectedWork previews={previews} />
        <DevlogSection initial={activity} />
        <HowIBuild />
        <Contact />
      </main>
      <SiteFooter />
    </div>
  );
}
